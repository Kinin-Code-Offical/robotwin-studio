        // A few upper-half A00 symbols, row-major (bits 4..0, left to right).
        private static readonly Dictionary<byte, byte[]> Upper = new Dictionary<byte, byte[]>
        {
            [0xDF] = new byte[] { 0x1C, 0x14, 0x1C, 0x00, 0x00, 0x00, 0x00, 0x00 }, // degree
            [0xE0] = new byte[] { 0x00, 0x00, 0x09, 0x15, 0x12, 0x12, 0x0D, 0x00 }, // alpha
            [0xE1] = new byte[] { 0x0A, 0x00, 0x0E, 0x01, 0x0F, 0x11, 0x0F, 0x00 }, // a umlaut
            [0xE2] = new byte[] { 0x00, 0x00, 0x0E, 0x11, 0x1E, 0x11, 0x1E, 0x10 }, // beta
            [0xE4] = new byte[] { 0x00, 0x00, 0x11, 0x11, 0x11, 0x13, 0x1D, 0x10 }, // mu
            [0xEF] = new byte[] { 0x0A, 0x00, 0x0E, 0x11, 0x11, 0x11, 0x0E, 0x00 }, // o umlaut
            [0xF4] = new byte[] { 0x00, 0x0E, 0x11, 0x11, 0x11, 0x0A, 0x1B, 0x00 }, // omega
            [0xF5] = new byte[] { 0x0A, 0x00, 0x11, 0x11, 0x11, 0x13, 0x0D, 0x00 }, // u umlaut
            [0xF7] = new byte[] { 0x00, 0x00, 0x1F, 0x0A, 0x0A, 0x0A, 0x13, 0x00 }, // pi
            [0xFD] = new byte[] { 0x00, 0x04, 0x00, 0x1F, 0x00, 0x04, 0x00, 0x00 }, // division
            [0xFF] = new byte[] { 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F }, // full block
        };

        private const string UpperChars =
            "αäβεμσρg√¹jˣ¢£ñöpqθ∞ΩüΣπxy千万円÷ █"; // 0xE0-0xFF

        /// <summary>
        /// The 8 pixel rows of <paramref name="code"/> (bits 4..0 = left to right). Codes 0-15
        /// are the user characters 0-7 (8-15 mirror 0-7) taken from <paramref name="cgram"/>
        /// (64 bytes) when given, blank otherwise.
        /// </summary>
        public static byte[] Glyph(byte code, byte[]? cgram = null)
        {
            var rows = new byte[8];
            if (code < 0x10)
            {
                if (cgram == null) return rows;
                int baseIndex = (code & 7) * 8;
                for (int r = 0; r < 8 && baseIndex + r < cgram.Length; r++) rows[r] = (byte)(cgram[baseIndex + r] & 0x1F);
                return rows;
            }

            if (code >= 0x20 && code <= 0x7F)
            {
                int offset = (code - 0x20) * 5;
                for (int col = 0; col < 5; col++)
                {
                    byte bits = Ascii[offset + col];
                    for (int r = 0; r < 7; r++)
                    {
                        if ((bits & (1 << r)) != 0) rows[r] |= (byte)(0x10 >> col);
                    }
                }

                return rows;
            }

            if (Upper.TryGetValue(code, out var glyph)) Array.Copy(glyph, rows, 8);
            return rows;
        }

        /// <summary>Unicode for an A00 character code; user characters (0-15) map to (char)0-(char)7.</summary>
        public static char ToChar(byte code)
        {
            if (code < 0x10) return (char)(code & 7);
            if (code < 0x20) return ' ';
            switch (code)
            {
                case 0x5C: return '¥';
                case 0x7E: return '→';
                case 0x7F: return '←';
            }

            if (code < 0x80) return (char)code;
            if (code <= 0xA0) return ' ';
            if (code == 0xDF) return '°';
            if (code < 0xE0) return (char)(0xFF61 + (code - 0xA1)); // half-width katakana (JIS X 0201)
            return UpperChars[code - 0xE0];
        }
    }
